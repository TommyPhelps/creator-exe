#!/usr/bin/env python3
"""Generates src/domain/thumbnails/fontMetrics.ts from the bundled fonts in public/fonts.

Advance widths (ASCII and common punctuation) let the thumbnail engine measure
and fit text without a browser, so concepts never overflow. Run after changing fonts.
"""
import json, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = [
    ("Lato", "Lato-Black.ttf", None),
    ("Anton", "Anton-Regular.ttf", None),
    ("Archivo Black", "ArchivoBlack-Regular.ttf", None),
    ("Bangers", "Bangers-Regular.ttf", None),
    ("Luckiest Guy", "LuckiestGuy-Regular.ttf", None),
    ("Permanent Marker", "PermanentMarker-Regular.ttf", None),
    ("Cinzel", "Cinzel.ttf", {"wght": 700}),
]
CHARS = [chr(c) for c in range(32, 127)] + list("’“”…–—éèáàüöä")

out = {}
for family, file, axes in FONTS:
    f = TTFont(ROOT / "public" / "fonts" / file)
    if axes:
        f = instancer.instantiateVariableFont(f, axes)
    upm = f["head"].unitsPerEm
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    os2 = f["OS/2"]
    widths = {}
    for ch in CHARS:
        g = cmap.get(ord(ch))
        if g:
            widths[ch] = round(hmtx[g][0] / upm, 4)
    cap = getattr(os2, "sCapHeight", 0) or round(upm * 0.7)
    out[family] = {
        "ascent": round(os2.sTypoAscender / upm, 4),
        "descent": round(-os2.sTypoDescender / upm, 4),
        "capHeight": round(cap / upm, 4),
        "fallback": round(sum(widths.values()) / max(1, len(widths)), 4),
        "widths": widths,
        "file": file,
        "weight": axes["wght"] if axes else (900 if family == "Lato" else 400),
        "lower": all(ord(c) in cmap for c in "abc") and family not in ("Bangers", "Luckiest Guy"),
    }

ts = "// Generated by scripts/font-metrics.py from public/fonts. Do not edit by hand.\n"
ts += "// Advance widths are fractions of the font size (em).\n\n"
ts += "export interface FontMetrics { ascent: number; descent: number; capHeight: number; fallback: number; widths: Record<string, number>; file: string; weight: number; lower: boolean }\n\n"
ts += "export const FONT_METRICS: Record<string, FontMetrics> = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
(ROOT / "src" / "domain" / "thumbnails" / "fontMetrics.ts").write_text(ts, encoding="utf-8")
print("wrote", len(out), "fonts")
